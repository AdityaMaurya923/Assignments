public class Main {
    public static void main(String[] args) {
        int steps = 0;

        // Time complexity: O(n) - one loop that runs n times
        for (int i = 1; i <= 10; i++) {
            steps++;
        }

        System.out.println("Steps: " + steps);
    }
}
